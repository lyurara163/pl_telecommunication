/**
 * 求严格小于 n 的最大素数（用于 Type1 长 ZC 序列的 n_ZC）。
 *
 * 【输入】
 *   n : 序列长度上界（通常 m_zc ≥ 36）
 *
 * 【算法】
 *   从 n-1 向下试除至 2，首个通过素性检验的 p 即为 n_ZC。
 *
 * 【返回】
 *   最大素数；若 n≤3 则兜底返回 2
 */
static Ushort ufeq_largest_prime_lt(Ushort n)
{
    Ushort p = 0;    /* 候选素数，从 n-1 递减 */
    Ushort d = 0;    /* 试除因子 */
    int prime = 0;   /* 当前 p 是否为素数 */

    for (p = (Ushort)(n - 1); p >= 2; --p) {
        prime = 1;
        for (d = 2; (Uint)d * d <= (Uint)p; ++d) { /* 只需试除到 √p */
            if ((p % d) == 0) {
                prime = 0;
                break;
            }
        }
        if (prime) {
            return p;
        }
    }
    return 2; /* 兜底：无更大素数时用 2 */
}

/**
 * 按 3GPP 规范生成长度为 M_ZC 的 Low-PAPR 基序列。
 *
 * 【输入】
 *   type         : 1=Type1（phi/ZC），2=Type2（IDFT）
 *   u            : 根索引 / 组号，有效范围 0..29
 *   v            : 预留（当前未使用）
 *   alpha        : 循环移位相位斜率，输出乘 e^{j·alpha·n}
 *   delta        : 预留（当前未使用）
 *   m_zc         : 序列长度 M_ZC
 *   out          : 输出复数缓冲
 *   out_capacity : out 可容纳元素个数
 *
 * 【输出】
 *   out       : 长度为 m_zc 的 Low-PAPR 序列
 *   out_count : 实际写出元素个数（= m_zc）
 *
 * 【Type1 算法要点】
 *   M∈{6,12,18,24}：查 phi 表，r(n)=exp(j·phi·π/4)
 *   M=30：二次相位 ZC 变体，指数含 u·(n+1)(n+2)/31
 *   M≥36：n_ZC=小于 M 的最大素数，r(n)=exp(-j·π·u·m(m+1)/n_ZC)，m=n mod n_ZC
 *   最后统一乘 e^{j·alpha·n}
 *
 * 【Type2 算法要点】
 *   M=6：查 phi_type2，相位 = phi·π/8
 *   M∈{12,18,24}：查比特表 b，构造 r~(i)
 *   M≥30：Gold 序列 x1^x2 生成比特
 *   对 r~ 做归一化 DFT（IDFT）：r^(k)=1/√M · Σ r~(i)·exp(-j2πik/M)
 *   再乘 e^{j·alpha·n} 写入 out
 */
ufeq_status_t ufeq_low_papr_generate(Uchar type,
                                     Uchar u,
                                     Uchar v,
                                     float alpha,
                                     Uchar delta,
                                     Ushort m_zc,
                                     ufeq_cfloat_t *out,
                                     Ushort out_capacity,
                                     Ushort *out_count)
{
    Ushort n = 0;              /* 输出样本索引 / Type1 时域索引 */
    Ushort i = 0;              /* Type2 时域索引 / DFT 求和索引 */
    Ushort k = 0;              /* Type2 频域（IDFT 输出）索引 */
    Ushort m = 0;              /* Type1 长序列：n mod n_ZC */
    Ushort n_zc = 0;           /* Type1 长序列 ZC 长度（最大素数） */
    const int8_t *phi = NULL;  /* Type1/Type2(M=6) phi 查表指针 */
    const Uchar *bits = NULL;  /* Type2(M=12/18/24) 比特表指针 */
    float ph = 0.0;            /* 基序列相位（弧度） */
    float base_re = 0.0;       /* 基序列 cos(ph) */
    float base_im = 0.0;       /* 基序列 sin(ph) */
    float ar = 0.0;            /* alpha 旋转 cos(alpha·n) */
    float ai = 0.0;            /* alpha 旋转 sin(alpha·n) */
    float br = 0.0;            /* 中间实部（Type1 长序列 / Type2 构造） */
    float bi = 0.0;            /* 中间虚部 */
    float q = 0.0;             /* Type1 长序列根索引 u（浮点） */
    float inv = 0.0;           /* IDFT 归一化因子 1/√M */
    float s = 0.0;             /* Type2：比特映射 ±1 */
    float ang = 0.0;           /* Type2：附加相位 π·i/2 或 DFT 旋转角 */
    ufeq_cfloat_t r_tilde[4096] = {{0}}; /* Type2 时域序列 r~ */
    ufeq_cfloat_t r_hat[4096] = {{0}};   /* Type2 IDFT 后 r^ */
    ufeq_cfloat_t sum = {0};   /* DFT 累加和 */
    ufeq_cfloat_t tw = {0};  /* DFT 旋转因子 exp(-j2πik/M) */
    Uint x1 = 0;               /* Gold 序列寄存器 1 */
    Uint x2 = 0;               /* Gold 序列寄存器 2（初值=u） */
    Uint nb = 0;               /* Gold 反馈比特 */
    Uchar cbit = 0;            /* x1^x2 当前输出比特 */

    (void)v;     /* API 预留参数，规范扩展用 */
    (void)delta;
    if (out == NULL || out_count == NULL || m_zc == 0 || u > 29) {
        return ufeq_fail("low_papr", "invalid_arg");
    }
    if (m_zc > out_capacity) {
        return ufeq_fail("low_papr", "buffer_small");
    }

    if (type == 1) {
        phi = NULL;
        if (m_zc == 6) {
            phi = g_phi_a1_6[u];
        } else if (m_zc == 12) {
            phi = g_phi_a1_12[u];
        } else if (m_zc == 18) {
            phi = g_phi_a1_18[u];
        } else if (m_zc == 24) {
            phi = g_phi_a1_24[u];
        }
        if (phi != NULL) {
            /* Type1 短序列：r(n)=exp(j·phi[n]·π/4)，再乘 alpha 旋转 */
            for (n = 0; n < m_zc; ++n) {
                ph = (float)phi[n] * (float)M_PI / 4.0;
                base_re = cosf(ph);
                base_im = sinf(ph);
                ar = cosf(alpha * (float)n); /* e^{j·alpha·n} */
                ai = sinf(alpha * (float)n);
                out[n] = ufeq_cf(base_re * ar - base_im * ai, base_re * ai + base_im * ar);
            }
        } else if (m_zc == 30) {
            /* Type1 M=30：特殊二次相位，分母 31 */
            for (n = 0; n < m_zc; ++n) {
                ph = -(float)M_PI * (float)u * (float)(n + 1) * (float)(n + 2) / 31.0;
                ar = cosf(alpha * (float)n);
                ai = sinf(alpha * (float)n);
                out[n] = ufeq_cf(cosf(ph) * ar - sinf(ph) * ai, cosf(ph) * ai + sinf(ph) * ar);
            }
        } else if (m_zc >= 36) {
            /* Type1 长序列：ZC，长度 n_ZC 为小于 m_zc 的最大素数 */
            n_zc = ufeq_largest_prime_lt(m_zc);
            q = (float)u;
            for (n = 0; n < m_zc; ++n) {
                m = (Ushort)(n % n_zc); /* 规范：m = n mod n_ZC */
                ph = -(float)M_PI * q * (float)m * ((float)m + 1.0) / (float)n_zc;
                br = cosf(ph);
                bi = sinf(ph);
                ar = cosf(alpha * (float)n);
                ai = sinf(alpha * (float)n);
                out[n] = ufeq_cf(br * ar - bi * ai, br * ai + bi * ar);
            }
        } else {
            return ufeq_fail("low_papr", "invalid_config"); /* 不支持的 M_ZC */
        }
    } else if (type == 2) {
        if (m_zc > 4096) {
            return ufeq_fail("low_papr", "unsupported_length");
        }
        if (m_zc == 6) {
            /* Type2 M=6：phi·π/8 直接得 r~ */
            for (i = 0; i < m_zc; ++i) {
                ph = (float)g_phi_type2_6[u][i] * (float)M_PI / 8.0;
                r_tilde[i] = ufeq_cf(cosf(ph), sinf(ph));
            }
        } else if (m_zc == 12 || m_zc == 18 || m_zc == 24) {
            /* Type2 中等长度：比特表 → ±1/√2，再乘 e^{j·π·i/2} */
            bits = NULL;
            if (m_zc == 12) {
                bits = g_b_type2_12[u];
            } else if (m_zc == 18) {
                bits = g_b_type2_18[u];
            } else {
                bits = g_b_type2_24[u];
            }
            for (i = 0; i < m_zc; ++i) {
                s = (bits[i] == 0) ? 1.0 : -1.0; /* b=0→+1，b=1→-1 */
                ang = (float)M_PI / 2.0 * (float)i; /* 规范附加相位 */
                br = s / sqrtf(2.0);
                bi = s / sqrtf(2.0);
                r_tilde[i] = ufeq_cf(br * cosf(ang) - bi * sinf(ang), br * sinf(ang) + bi * cosf(ang));
            }
        } else if (m_zc >= 30) {
            /* Type2 长序列：Gold 序列生成比特，再同中等长度构造 r~ */
            x1 = 1;
            x2 = (Uint)u & 0x7fffffff; /* c_init 与 u 相关 */
            for (i = 0; i < 1600; ++i) { /* 跳过前 1600 比特（规范要求） */
                nb = ((x1 >> 3) ^ x1) & 1;
                x1 = (x1 >> 1) | (nb << 30);
                nb = ((x2 >> 3) ^ (x2 >> 2) ^ (x2 >> 1) ^ x2) & 1;
                x2 = (x2 >> 1) | (nb << 30);
            }
            for (i = 0; i < m_zc; ++i) {
                cbit = (Uchar)((x1 ^ x2) & 1); /* 输出比特 = x1(n) XOR x2(n) */
                s = (cbit == 0) ? 1.0 : -1.0;
                ang = (float)M_PI / 2.0 * (float)i;
                br = s / sqrtf(2.0);
                bi = s / sqrtf(2.0);
                r_tilde[i] = ufeq_cf(br * cosf(ang) - bi * sinf(ang), br * sinf(ang) + bi * cosf(ang));
                /* 推进 Gold 寄存器，生成下一位 */
                nb = ((x1 >> 3) ^ x1) & 1;
                x1 = (x1 >> 1) | (nb << 30);
                nb = ((x2 >> 3) ^ (x2 >> 2) ^ (x2 >> 1) ^ x2) & 1;
                x2 = (x2 >> 1) | (nb << 30);
            }
        } else {
            return ufeq_fail("low_papr", "invalid_config");
        }
        /* 对 r~ 做归一化 DFT（即 IDFT）：r^(k) = (1/√M) Σ_i r~(i)·exp(-j2πik/M) */
        inv = 1.0 / sqrtf((float)m_zc);
        for (k = 0; k < m_zc; ++k) {
            sum = ufeq_cf(0.0, 0.0);
            for (i = 0; i < m_zc; ++i) {
                ang = -2.0 * (float)M_PI * (float)i * (float)k / (float)m_zc;
                tw = ufeq_cf(cosf(ang), sinf(ang));
                sum = ufeq_cf_add(sum, ufeq_cf_mul(r_tilde[i], tw));
            }
            r_hat[k] = ufeq_cf_scale(sum, inv);
        }
        /* 频域 r^ 再经 alpha 循环移位写入 out */
        for (n = 0; n < m_zc; ++n) {
            ar = cosf(alpha * (float)n);
            ai = sinf(alpha * (float)n);
            out[n] = ufeq_cf(r_hat[n].re * ar - r_hat[n].im * ai, r_hat[n].re * ai + r_hat[n].im * ar);
        }
    } else {
        return ufeq_fail("low_papr", "invalid_config"); /* type 非 1/2 */
    }

    *out_count = m_zc;
    return ufeq_status_ok;
}
